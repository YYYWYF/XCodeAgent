"""把 canonical application.json 的公开字段确定性投影到前端模板。"""

from __future__ import annotations

import hashlib
import json
import os
import re
import stat
import tempfile
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

from app.services.application_config.repository import ApplicationConfigRepository

APP_CONFIG_TARGET = Path("frontend/src/config/app.generated.ts")
_COLOR_PATTERN = re.compile(r"^#[0-9A-Fa-f]{6}$")
SUPPORTED_APPLICATION_ICONS = frozenset(
    {
        "AppstoreOutlined",
        "DesktopOutlined",
        "DashboardOutlined",
        "ShopOutlined",
        "ShoppingOutlined",
        "TeamOutlined",
        "UserOutlined",
        "ToolOutlined",
        "CloudOutlined",
        "MessageOutlined",
        "BankOutlined",
        "FundOutlined",
    }
)


class ApplicationConfigProjectionError(ValueError):
    """表示公开应用配置无法安全投影到模板。"""

    def __init__(self, code: str, message: str) -> None:
        """保存稳定错误码，并生成可直接展示的错误消息。"""

        self.code = code
        super().__init__(f"{code}：{message}")


@dataclass(frozen=True)
class ApplicationConfigProjectionResult:
    """描述一次幂等投影的有限公开结果。"""

    status: Literal["CHANGED", "NO_CHANGE", "SKIPPED_NO_TEMPLATE"]
    config_revision: int
    content_sha256: str | None

    def as_dict(self) -> dict[str, Any]:
        """转换为前后端协议使用的 camelCase 字典。"""

        return {
            "status": self.status,
            "configRevision": self.config_revision,
            "contentSha256": self.content_sha256,
        }


def compile_public_app_config(application: dict[str, Any]) -> dict[str, Any]:
    """严格提取唯一允许进入公开前端源码的三个配置字段。"""

    if not isinstance(application, dict):
        raise ApplicationConfigProjectionError("APP_CONFIG_INVALID", "application.json 必须是对象。")
    app_name = application.get("appName")
    if not isinstance(app_name, str) or not app_name.strip():
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_INVALID", "application.json.appName 必须是非空字符串。"
        )
    app_icon = application.get("appIcon")
    if not isinstance(app_icon, str) or app_icon not in SUPPORTED_APPLICATION_ICONS:
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_INVALID", "application.json.appIcon 不是受支持的应用图标。"
        )
    theme = application.get("theme")
    primary_color = theme.get("primaryColor") if isinstance(theme, dict) else None
    if not isinstance(primary_color, str) or _COLOR_PATTERN.fullmatch(primary_color) is None:
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_INVALID",
            "application.json.theme.primaryColor 必须是 #RRGGBB 格式。",
        )
    return {
        "app": {"name": app_name, "icon": app_icon},
        "theme": {"primaryColor": primary_color},
    }


def render_public_app_config(application: dict[str, Any]) -> str:
    """使用 JSON 字符串转义生成稳定、不可注入的 TypeScript 配置源码。"""

    value = compile_public_app_config(application)
    serialized = json.dumps(value, ensure_ascii=False, indent=2, separators=(",", ": "))
    # JSON 允许这两个字符直接出现，但 JavaScript 会把它们解释为行分隔符。
    serialized = serialized.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    return (
        "// AUTO-GENERATED BY XCODEAGENT. DO NOT EDIT BY HAND.\n"
        "import type { AppConfig } from './types';\n\n"
        f"export const generatedConfig = {serialized} satisfies AppConfig;\n"
    )


def project_template_app_config(
    template_root: str | Path,
    application: dict[str, Any],
    *,
    before_replace: Callable[[], None] | None = None,
) -> ApplicationConfigProjectionResult:
    """只在已有模板目标上原子写入公开配置，拒绝路径逃逸和符号链接。"""

    revision = _config_revision(application)
    root = _validated_root(template_root)
    target = _validated_target(root)
    content = render_public_app_config(application)
    digest = hashlib.sha256(content.encode("utf-8")).hexdigest()
    try:
        current = target.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_TARGET_UNREADABLE", "无法读取 frontend/src/config/app.generated.ts。"
        ) from exc
    if current == content:
        if before_replace is not None:
            before_replace()
        return ApplicationConfigProjectionResult("NO_CHANGE", revision, digest)

    temporary: Path | None = None
    try:
        descriptor, name = tempfile.mkstemp(
            prefix=".app.generated.ts.", suffix=".tmp", dir=target.parent, text=True
        )
        temporary = Path(name)
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, stat.S_IMODE(target.stat().st_mode))
        if before_replace is not None:
            before_replace()
        os.replace(temporary, target)
        temporary = None
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    return ApplicationConfigProjectionResult("CHANGED", revision, digest)


def project_workspace_app_config(
    workspace_root: str | Path,
    *,
    expected_config_revision: int,
) -> ApplicationConfigProjectionResult:
    """读取工作区唯一配置并以修订号 CAS 方式同步已有模板。"""

    root = _validated_root(workspace_root)
    application = ApplicationConfigRepository(root).load()
    revision = _config_revision(application)
    if revision != expected_config_revision:
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_REVISION_CONFLICT",
            f"期望 configRevision={expected_config_revision}，当前为 {revision}。",
        )
    frontend = root / "frontend"
    template_markers = (frontend, root / "backend", root / ".git")
    if not any(path.exists() or path.is_symlink() for path in template_markers):
        return ApplicationConfigProjectionResult("SKIPPED_NO_TEMPLATE", revision, None)

    def assert_revision_current() -> None:
        """在原子替换紧邻位置再次验证 canonical 配置修订。"""

        current_revision = _config_revision(ApplicationConfigRepository(root).load())
        if current_revision != revision:
            raise ApplicationConfigProjectionError(
                "APP_CONFIG_REVISION_CONFLICT",
                f"投影期间 configRevision 已从 {revision} 变为 {current_revision}。",
            )

    result = project_template_app_config(
        root,
        application,
        before_replace=assert_revision_current,
    )
    return result


def validate_projected_app_config(
    template_root: str | Path,
    application: dict[str, Any],
) -> None:
    """验证目标是普通文件且内容与冻结配置快照逐字节一致。"""

    root = _validated_root(template_root)
    target = _validated_target(root)
    try:
        current = target.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_TARGET_UNREADABLE", "无法读取 frontend/src/config/app.generated.ts。"
        ) from exc
    if current != render_public_app_config(application):
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_PROJECTION_MISMATCH", "app.generated.ts 与当前 application.json 不一致。"
        )


def _config_revision(application: dict[str, Any]) -> int:
    """读取并严格校验用于并发控制的配置修订号。"""

    revision = application.get("configRevision") if isinstance(application, dict) else None
    if type(revision) is not int or revision < 1:
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_INVALID", "application.json.configRevision 必须是大于零的整数。"
        )
    return revision


def _validated_target(root: Path) -> Path:
    """限定唯一目标路径，并拒绝任一受控目录或文件为符号链接。"""

    if not root.is_dir() or root.is_symlink():
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_TEMPLATE_INVALID", "模板根必须是已存在且非符号链接的目录。"
        )
    current = root
    for part in APP_CONFIG_TARGET.parts[:-1]:
        current = current / part
        if not current.is_dir() or current.is_symlink():
            if not current.exists() and not current.is_symlink():
                raise ApplicationConfigProjectionError(
                    "APP_CONFIG_TARGET_MISSING", "旧工程缺少 frontend/src/config/app.generated.ts。"
                )
            raise ApplicationConfigProjectionError(
                "APP_CONFIG_TARGET_INVALID", "应用配置目标的父目录必须是普通目录。"
            )
    target = root / APP_CONFIG_TARGET
    if not target.is_file() or target.is_symlink():
        if not target.exists() and not target.is_symlink():
            raise ApplicationConfigProjectionError(
                "APP_CONFIG_TARGET_MISSING", "旧工程缺少 frontend/src/config/app.generated.ts。"
            )
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_TARGET_INVALID", "应用配置目标必须是普通文件。"
        )
    return target


def _validated_root(value: str | Path) -> Path:
    """拒绝符号链接根目录，并返回规范化的真实模板根。"""

    candidate = Path(value).expanduser()
    if candidate.is_symlink():
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_TEMPLATE_INVALID", "模板根不能是符号链接。"
        )
    root = candidate.resolve()
    if not root.is_dir():
        raise ApplicationConfigProjectionError(
            "APP_CONFIG_TEMPLATE_INVALID", "模板根必须是已存在目录。"
        )
    return root
